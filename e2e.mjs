import { chromium } from 'playwright';
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1280, height: 800 } });
const errs=[]; p.on('pageerror',e=>errs.push(e.message)); p.on('request',r=>{ if(!r.url().startsWith('http://localhost:4173')) errs.push('NET '+r.url()); });
await p.goto('http://localhost:4173'); await p.evaluate(()=>localStorage.clear()); await p.reload(); await p.waitForTimeout(800);
const coins = async()=>Number(await p.textContent('#coin-count'));
for (let i=0;i<8;i++) await p.click('#spawn-btn');
await p.waitForTimeout(500); console.log('after spawn coins', await coins());
await p.screenshot({ path: 'shots/01-board.png' });
const cells = await p.evaluate(()=>window.__state.cells);
const ones = cells.map((c,i)=>c===1?i:-1).filter(i=>i>=0);
const box = await p.locator('canvas').boundingBox();
const at = i => ({ x: box.x + 12 + (i%6)*96 + 48, y: box.y + 12 + Math.floor(i/6)*96 + 48 });
const before = await coins();
const a = at(ones[0]), c = at(ones[1]);
await p.mouse.move(a.x,a.y); await p.mouse.down(); await p.mouse.move((a.x+c.x)/2,(a.y+c.y)/2,{steps:10}); await p.mouse.move(c.x,c.y,{steps:10}); await p.mouse.up();
await p.waitForTimeout(300);
const after = await coins(); console.log('merge coins', before, '->', after, 'cell', ones[1], '=', (await p.evaluate(()=>window.__state.cells))[ones[1]]);
await p.screenshot({ path: 'shots/02-merge.png' });
await p.waitForTimeout(1200);
const b2 = await coins(); await p.click('#shop-luckySpawn'); await p.waitForTimeout(250);
console.log('buy Lucky Spawn coins', b2, '->', await coins(), 'msg', await p.textContent('#msg'), 'tier2 count', (await p.evaluate(()=>window.__state.cells)).filter(x=>x===2).length);
await p.screenshot({ path: 'shots/03-shop-buy.png' });
await p.reload(); await p.waitForTimeout(500); console.log('after reload coins', await coins());
console.log('errors', errs); await b.close();
